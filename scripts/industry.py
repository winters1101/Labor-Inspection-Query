def classify_org(name: str) -> str:
    if "財團法人" in name:
        return "財團法人"
    if "社團法人" in name or re.search(r"協會|公會|工會|學會", name):
        return "社團法人"
    if re.search(r"政府|公所|學校|大學|國小|國中|高中|醫院|農會|漁會", name) and "公司" not in name:
        return "學校、政府及公營機構"
    if "股份有限公司" in name:
        return "股份有限公司"
    if "有限公司" in name or "公司" in name:
        return "有限公司"
    if "即" in name or re.search(r"商行|商號|行|店|社|館|坊|攤|廠|屋|院|所", name):
        return "獨資、合夥商號"
    return "其他"
