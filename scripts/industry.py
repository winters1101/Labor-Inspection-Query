_COMPILED = [(name, re.compile(pat)) for name, pat in INDUSTRY_RULES]

INDUSTRIES = list(dict.fromkeys(name for name, _ in INDUSTRY_RULES)) + [OTHER]


def _core_name(name: str) -> str:
    """去除負責人姓名等附註，只留事業單位名稱本體。"""
    s = name
    # 「王小明即小明小吃店」→ 取「即」後的商號
    if "即" in s:
        s = s.split("即", 1)[1]
    # 去除括號中的負責人
    s = re.sub(r"[（(][^()（）]*[)）]?$", "", s)
    return s


def classify_industry(name: str) -> str:
    core = _core_name(name)
    for label, rx in _COMPILED:
        if rx.search(core):
            return label
    return OTHER


